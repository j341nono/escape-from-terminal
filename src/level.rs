use crate::{geom::Vec2, map::Map};

pub struct Level {
    pub map: Map,
    pub player_start: Vec2,
    pub player_angle: f32,
}

pub fn training_sector() -> Result<Level, String> {
    let map = Map::from_ascii(&[
        "#################################",
        "#...........#...................#",
        "#...........#...................#",
        "#...#####...#....###########....#",
        "#.......#...#..............#....#",
        "#####...#...##########.....#....#",
        "#.......#.................##....#",
        "#.......########..........##....#",
        "#.........................##....#",
        "#...###########...###########...#",
        "#...#.........#.................#",
        "#...#.........#.................#",
        "#...#....######....##########...#",
        "#...#.......................#...#",
        "#...###########.............#...#",
        "#..............#####........#...#",
        "#..............#............#...#",
        "#...############....#########...#",
        "#...............................#",
        "#...............................#",
        "#################################",
    ])?;

    Ok(Level {
        map,
        player_start: Vec2::new(3.5, 2.5),
        player_angle: 0.0,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bundled_level_is_valid() {
        let level = training_sector().expect("bundled level should parse");
        assert!(level.map.is_walkable_position(level.player_start, 0.22));
        assert_eq!((level.map.width(), level.map.height()), (33, 21));
    }
}
